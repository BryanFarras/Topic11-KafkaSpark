#!/usr/bin/env python3
"""
Verification script for Parquet output generated by Spark Structured Streaming.
Topic 11 — Kafka & PySpark Structured Streaming Ingestion Pipeline

Reads Parquet dataset from hasil/klik_per_menit, displays schema, record count,
and prints rows ordered by window interval.
"""

import os
import sys
from pyspark.sql import SparkSession


def verify_parquet(parquet_path="hasil/klik_per_menit"):
    print(f"=== Verifying Parquet Output at: {parquet_path} ===")
    
    if not os.path.exists(parquet_path):
        print(f"[ERROR] Directory '{parquet_path}' does not exist.")
        return 1

    spark = (
        SparkSession.builder
        .appName("verify-parquet")
        .master("local[*]")
        .getOrCreate()
    )
    spark.sparkContext.setLogLevel("WARN")

    try:
        df = spark.read.parquet(parquet_path)
        
        print("\n--- Parquet Schema ---")
        df.printSchema()

        total_rows = df.count()
        print(f"\n--- Total Rows: {total_rows} ---")

        if total_rows > 0:
            print("\n--- Persisted Records (Ordered by window) ---")
            df.orderBy("window").show(100, truncate=False)
        else:
            print("[WARN] Parquet dataset exists but contains 0 records.")
            print("(Note: Parquet in append mode writes data only after the 2-minute watermark closes a window).")

        return 0

    except Exception as e:
        print(f"[ERROR] Failed to read Parquet data: {e}")
        return 1

    finally:
        spark.stop()
        print("[Verify] Completed.")


if __name__ == "__main__":
    target_path = sys.argv[1] if len(sys.argv) > 1 else "hasil/klik_per_menit"
    sys.exit(verify_parquet(target_path))
